/** The compiled Book Distiller Ingestion graph, generated by LangGraph without running its nodes. */
export async function fetchAgenticGraph(): Promise<AgenticGraph> {
  const result = await client.request({
    method: "GET",
    url: "/api/v1/bd/ingestion/agentic-graph",
    throwOnError: true,
  });
  return agenticGraphSchema.parse(result.data);
}

