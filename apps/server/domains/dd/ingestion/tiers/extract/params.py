"""Chrome + content-root selector lists for the HTML→MD pipeline."""
from __future__ import annotations


# Tags to strip outright before conversion. Covers the usual chrome that
# would otherwise leak into the markdown body: navs, sidebars, footers,
# noscript fallbacks, scripts, styles, forms, and SVG icons.
CHROME_SELECTORS: tuple[str, ...] = (
    "script", "style", "noscript", "iframe", "form", "svg",
    "nav", "header", "footer", "aside",
    '[role="navigation"]', '[role="banner"]', '[role="contentinfo"]',
    '[role="complementary"]', '[role="search"]',
    ".nav", ".navigation", ".navbar", ".sidebar", ".menu",
    ".header", ".footer", ".breadcrumb",
    ".toc", ".tocify", ".table-of-contents",
    ".cookie", ".cookie-banner", ".cookies-banner",
    ".announce", ".announcement",
    ".search-form", ".searchbox",
    # What the sites in this tier were seen to leave in the page (2026-10-27, Tier 3 over seven docs):
    # buttons ("Back to top", "Copy page"), the host's own "not for print" marker, text only a screen reader reads (a
    # heading's "Section titled “Overview”"), Docusaurus' collapsed mobile "On this page", mkdocs-material's back-to-top
    # button, Grafana's breadcrumb and its feedback + related-articles footer, Mintlify's feedback bar and "Connect these
    # docs" box.
    "button",
    ".print-hidden", ".hidden-print", ".d-print-none", ".no-print", ".noprint",
    ".sr-only", ".visually-hidden", ".visuallyhidden", ".screen-reader-text", ".sl-anchor-link",
    ".theme-doc-toc-mobile", '[class*="tocCollapsible"]',
    ".md-top", ".md-nav", ".md-header", ".md-footer",
    ".docs__breadcrumb", ".docs__feedback",
    ".feedback-toolbar", ".source-links", "#page-context-menu",
    # Tier 4 (2026-10-27, eleven docs crawled): pydata-sphinx-theme's right-hand column (OpenVINO: "Edit on GitHub" on 517
    # pages, "On this page" on 294, a `.zip` download menu on 152), Celery's version banner, Sphinx-Gallery's download
    # footer and its "Computation times" section.
    ".bd-sidebar-secondary", ".sidebar-secondary-items", ".editthispage", ".onthispage", ".page-toc", ".download-docs",
    "div.deck",
    ".sphx-glr-footer", ".sphx-glr-timing", "#computation-times",
    # Seen on the second pass (2026-10-27): go.dev's breadcrumb list (`ol.SiteBreadcrumb`) heads 34 pages — any class with "breadcrumb"
    # in it (the case of its first letter varies) — typescriptlang.org's footer ("Was this page helpful?", "Last updated",
    # "Contributors to this page", "This page loaded in …") and consent banner, duckdb.org's search overlay, side menu and
    # "Edit this page" bar.
    '[class*="readcrumb"]',
    ".bottom-section-content", ".page-popup", "#cookie-banner", "#wcpConsentBannerCtrl",
    ".searchoverlay", ".sidenavigation", ".sidenav", ".pagemeta",
    # …and Sphinx-Gallery's "Gallery generated by Sphinx-Gallery" signature, which ended 49 of XGBoost's pages and is outside its footer div.
    ".sphx-glr-signature",
)

# Sphinx's `¶` permalink on every heading. Not a chrome selector: Tier 4's anchor split reads an `a.headerlink` in an `<h2>` as "the
# author meant this as a section", so it must survive until the page has been split; it goes when a page is converted to Markdown.
PERMALINK_SELECTORS: tuple[str, ...] = (".headerlink",)

# The viewcode `[source]` link Sphinx puts after every signature (`<a class="reference internal" href="…/_modules/…"><span
# class="viewcode-link">[source]</span></a>`): the link goes whole, not just its text.
VIEWCODE_SELECTOR = ".viewcode-link"

# A callout written as a `<div>` (Sphinx's `admonition note`, Docusaurus' `theme-admonition`): kept as a block quote with its title
# in bold, like the `<aside>` callouts. Matched by a class that starts with one of these.
ADMONITION_CLASS_PREFIXES: tuple[str, ...] = ("admonition", "theme-admonition")
ADMONITION_TITLE_CLASSES: tuple[str, ...] = ("admonition-title", "admonition-heading")
HEADING_TAGS: tuple[str, ...] = ("h1", "h2", "h3", "h4", "h5", "h6")

# An element a chrome selector matches INSIDE a heading is the heading's text, not page furniture — mdBook wraps every heading's
# text in `<a class="header">`, and `.header` is a chrome selector, so all 109 pages of the Rust book came out with an empty
# `#`. These are the exceptions: what a heading carries that is not its text (the permalink, hidden text, an icon).
HEADING_FURNITURE_SELECTORS: frozenset[str] = frozenset({
    ".headerlink", ".sl-anchor-link", ".sr-only", ".visually-hidden", ".visuallyhidden", ".screen-reader-text", "svg", "button",
})

# An `<aside>` that is a callout (Starlight's Note / Tip / Caution), not page furniture: kept, as a block quote. The
# tag is in CHROME_SELECTORS because most asides are sidebars and tables of contents; these are told apart by their
# class (or role), and one that also looks like a sidebar or a table of contents stays chrome.
CALLOUT_ASIDE_MARKERS: tuple[str, ...] = ("starlight-aside", "admonition", "callout", "alert", "note", "tip", "warning", "caution")
NOT_CALLOUT_MARKERS: tuple[str, ...] = ("sidebar", "toc", "contents", "on this page", "nav", "menu", "related", "footnote")

# What separates a page's name from its site's in a `<title>` ("Quick start | Grafana Tempo documentation").
TITLE_SEPARATORS: tuple[str, ...] = (" | ", " - ", " – ", " — ", " · ", " :: ", " « ", " » ")

# Common "main content" candidates — try these first before falling back to
# <body>. Many docs sites (Sphinx, mkdocs, Docusaurus, Nextra, GitBook,
# Mintlify) use one of these patterns.
CONTENT_SELECTORS: tuple[str, ...] = (
    "main",
    "article",
    '[role="main"]',
    "#content", "#main", "#main-content", "#docs-content",
    ".content", ".main", ".main-content", ".docs-content",
    ".markdown-body", ".prose",
    ".article", ".post", ".doc-content",
)
