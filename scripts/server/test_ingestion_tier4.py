# ---- the copy a re-ingestion replaces waits until the new one is done ------------------------------------------------------------------------
class FakeMinio:
    """Just the objects-by-prefix calls the backup uses."""

    def __init__(self):
        self.objects: dict[str, str] = {}

    async def read_text(self, key): return self.objects[key]
    async def list(self, prefix): return sorted(k for k in self.objects if k.startswith(prefix))

    async def list_subfolders(self, prefix):
        return sorted({k[len(prefix):].split("/", 1)[0] for k in self.objects if k.startswith(prefix) and "/" in k[len(prefix):]})

    async def copy_prefix(self, src, dst, skip_substring=None, **_):
        keys = [k for k in await self.list(src) if not (skip_substring and skip_substring in k)]
        for k in keys:
            self.objects[dst + k[len(src):]] = self.objects[k]
        return len(keys)

    async def delete_prefix(self, prefix):
        keys = await self.list(prefix)
        for k in keys:
            del self.objects[k]
        return len(keys)


def seed(minio: FakeMinio, label: str) -> None:
    keys = storage.keys
    minio.objects[keys.manifest_key("demo")] = '{"entries": [{"idx": 0}]}'
    minio.objects[keys.page_key("demo", 0, "intro")] = f"old page {label}"
    minio.objects[keys.raw_page_key("demo", 0, "intro")] = f"old raw {label}"
    minio.objects[keys.vault_manifest_key("demo", 0, "intro")] = f"old vault {label}"


def live(minio: FakeMinio) -> dict[str, str]:
    return {k: v for k, v in minio.objects.items() if not k.startswith("ingestion-backup/")}


async def backups() -> None:
    minio = FakeMinio()
    seed(minio, "v1")
    before = live(minio)
    backup_id = await storage.service.stash_old_copy(minio, "demo")
    check("starting a re-ingestion sets the old copy aside and empties the three places it lived", (backup_id is not None, live(minio)), (True, {}))
    check("…the backup holds the pages, the raw copies and the vaults", len(await minio.list(storage.keys.backup_prefix("demo", backup_id))), 4)
    minio.objects[storage.keys.page_key("demo", 0, "partial")] = "half a new run"
    restored = await storage.service.restore_old_copy(minio, "demo", backup_id)
    check("a failed run's leftovers are replaced by the old copy, exactly as it was", (restored, live(minio)), (4, before))
    await storage.service.drop_old_copy(minio, "demo")
    check("a finished run drops the backup", await storage.service.latest_backup(minio, "demo"), None)

    first = FakeMinio()
    check("a first ingestion has nothing to set aside", (await storage.service.stash_old_copy(first, "demo"), first.objects), (None, {}))

    crashed = FakeMinio()
    seed(crashed, "v1")
    kept = await storage.service.stash_old_copy(crashed, "demo")
    check("after a crash (a backup, and no finalized copy) the next run keeps that backup and makes no new one",
          (await storage.service.stash_old_copy(crashed, "demo"), await storage.service.latest_backup(crashed, "demo")), (kept, kept))
    seed(crashed, "v2")
    crashed.objects[storage.keys.backup_prefix("demo", "20200101T000000Z") + "pages/old.md"] = "an older backup"
    newer = await storage.service.stash_old_copy(crashed, "demo")
    check("a finalized copy is backed up over any older backup, which goes", await crashed.list_subfolders(storage.keys.backup_root("demo")), [newer])
    check("…and the backup is the finalized copy, not what it replaced", crashed.objects[storage.keys.backup_prefix("demo", newer) + "pages/pages/0000-intro.md"], "old page v2")
    check("restoring a backup that is gone touches nothing", await storage.service.restore_old_copy(crashed, "demo", "19990101T000000Z"), 0)

    # the dispatcher's wrapper: puts the copy back, and never raises
    wrapped = FakeMinio()
    seed(wrapped, "v1")
    await storage.service.stash_old_copy(wrapped, "demo")
    await ingestion.runtime.dispatch.service._restore_old_copy(wrapped, "demo")
    check("a failed run puts the old copy back and drops its backup", (storage.keys.page_key("demo", 0, "intro") in wrapped.objects, await storage.service.latest_backup(wrapped, "demo")), (True, None))

    class Broken(FakeMinio):
        async def list_subfolders(self, prefix): raise RuntimeError("minio is down")

    await ingestion.runtime.dispatch.service._restore_old_copy(Broken(), "demo")
    print("ok  …and a storage error while doing it is logged, not raised over the run's own error")


asyncio.run(backups())

print("\nall checks passed")
