"""Clear Docs Distiller's new and legacy MinIO namespaces for a clean rebuild.

Dry-run by default. Applying removes DD ingestion data, captures, Planner and
Synth outputs, and the shared DD caches. These can be regenerated by ingestion
and downstream DD runs.

    cd apps/server
    .venv/bin/python ../../scripts/server/clear_dd_storage.py
    .venv/bin/python ../../scripts/server/clear_dd_storage.py --apply
"""
from __future__ import annotations

import argparse
import asyncio
import os
import sys
from pathlib import Path

from dotenv import load_dotenv


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "apps" / "server"))
load_dotenv(ROOT / ".env", override=False)
os.environ.setdefault("MINIO_BUCKET_COELHONEXUS", "coelhonexus")

endpoint = os.environ.get("MINIO_ENDPOINT", "").strip()
if endpoint and "://" not in endpoint:
    scheme = "https" if os.environ.get("MINIO_USE_SSL", "").lower() in {"1", "true", "yes"} else "http"
    os.environ["MINIO_ENDPOINT"] = f"{scheme}://{endpoint}"

import infra  # noqa: E402


# DD-only prefixes in the shared coelhonexus bucket. `dd/` includes the new
# framework-first layout and its shared cache; the remaining roots are legacy.
PREFIXES = (
    "dd/",
    "ingestion/",
    "planner/",
    "synth/",
    "synth-cache/",
    "synth-vault/",
    "ingestion-backup/",
)


async def clear(*, apply: bool) -> int:
    storage = infra.minio.service.get_storage()
    print(f"bucket={storage.bucket} mode={'apply' if apply else 'dry-run'}")

    inventory = {prefix: await storage.list(prefix) for prefix in PREFIXES}
    for prefix, keys in inventory.items():
        print(f"{prefix}: {len(keys)} objects")
    if not apply:
        print("dry-run complete; no objects changed")
        return 0

    for prefix in PREFIXES:
        deleted = await storage.delete_prefix(prefix)
        print(f"deleted {prefix}: {deleted} objects")

    remaining = {prefix: await storage.list(prefix) for prefix in PREFIXES}
    leftovers = {prefix: len(keys) for prefix, keys in remaining.items() if keys}
    if leftovers:
        raise RuntimeError(f"DD prefixes still contain objects: {leftovers}")
    print("complete: DD storage is clear for a ground-up rebuild")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="delete all listed DD MinIO prefixes")
    args = parser.parse_args()
    return asyncio.run(clear(apply=args.apply))


if __name__ == "__main__":
    raise SystemExit(main())
